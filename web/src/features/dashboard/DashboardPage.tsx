/**
 * Overview dashboard: query CTA, recent runs, and the latest report —
 * FTSE company digest or query-driven findings, derived from real data.
 */
import { useEffect, useMemo, useState } from "react";
import { Link } from "react-router-dom";
import {
  ArrowRight,
  ArrowUpRight,
  Building2,
  ExternalLink,
  FileText,
  Flame,
  Newspaper,
  PlayCircle,
  SearchCheck,
  ThumbsDown,
  ThumbsUp,
} from "lucide-react";
import {
  Bar,
  BarChart,
  CartesianGrid,
  Cell,
  Pie,
  PieChart,
  ResponsiveContainer,
  Tooltip,
  XAxis,
  YAxis,
} from "recharts";
import { api, ApiError } from "../../lib/api";
import type { ArticleWithCompany, ReportDetail, ResearchRun } from "../../types";
import { formatConfidence, formatDate, hostOf, timeAgo } from "../../lib/format";
import {
  Alert,
  Badge,
  Button,
  Card,
  CardHeader,
  EmptyState,
  ErrorState,
  impactTone,
  LoadingState,
  sentimentTone,
  Stat,
} from "../../components/ui";
import ArticleDialog from "../../components/ArticleDialog";
import { isTerminal, RunStatusBadge } from "../runs/RunBits";

const SENTIMENT_COLORS: Record<string, string> = {
  positive: "#34d399",
  negative: "#f87171",
  neutral: "#fbbf24",
};
const IMPACT_COLORS: Record<string, string> = {
  high: "#f87171",
  medium: "#fbbf24",
  low: "#8b98b8",
};

type LoadState =
  | { kind: "loading" }
  | { kind: "error"; message: string }
  | { kind: "empty" }
  | { kind: "ready"; report: ReportDetail | null; runs: ResearchRun[]; activeRun: ResearchRun | null };

export default function DashboardPage() {
  const [state, setState] = useState<LoadState>({ kind: "loading" });

  const load = async () => {
    setState({ kind: "loading" });
    try {
      const [report, runs] = await Promise.all([
        api.latestReport(),
        api.runs(5).catch(() => ({ count: 0, runs: [] })),
      ]);
      const activeRun =
        runs.runs.find((r) => r.status === "running" || r.status === "queued") ?? null;
      setState({ kind: "ready", report, runs: runs.runs, activeRun });
    } catch (err) {
      if (err instanceof ApiError && err.status === 404) {
        // No reports yet — still show runs/CTA.
        try {
          const runs = await api.runs(5).catch(() => ({ count: 0, runs: [] }));
          const activeRun =
            runs.runs.find((r) => r.status === "running" || r.status === "queued") ?? null;
          if (runs.runs.length > 0) {
            setState({ kind: "ready", report: null, runs: runs.runs, activeRun });
            return;
          }
        } catch {
          /* fall through to empty */
        }
        setState({ kind: "empty" });
      } else {
        setState({
          kind: "error",
          message: err instanceof Error ? err.message : "Failed to load the dashboard.",
        });
      }
    }
  };

  useEffect(() => {
    load();
    // eslint-disable-next-line react-hooks/exhaustive-deps
  }, []);

  if (state.kind === "loading") return <LoadingState message="Loading latest research…" />;
  if (state.kind === "error") return <ErrorState message={state.message} onRetry={load} />;
  if (state.kind === "empty")
    return (
      <div className="space-y-6">
        <QueryCta />
        <EmptyState
          title="No research reports yet"
          message="Ask your first research question to populate this dashboard. Reports are generated by the Python pipeline and read live by this UI."
          icon={<Newspaper className="h-6 w-6" />}
          action={
            <Link to="/runs">
              <Button variant="primary">Start researching</Button>
            </Link>
          }
        />
      </div>
    );

  return (
    <div className="space-y-6">
      <QueryCta />
      {state.activeRun && (
        <Alert tone="info">
          A research run is currently {state.activeRun.status}.{" "}
          <Link to={`/runs/${state.activeRun.run_id}`} className="underline">
            View live progress
          </Link>
        </Alert>
      )}
      {state.report ? (
        state.report.summary.report_type === "query" ? (
          <QueryReportSummary report={state.report} />
        ) : (
          <FtseReportSummary report={state.report} activeRun={state.activeRun} />
        )
      ) : (
        <EmptyState
          title="No reports yet"
          message="Completed research runs will appear here."
          icon={<Newspaper className="h-6 w-6" />}
        />
      )}
      <RecentRuns runs={state.runs} />
    </div>
  );
}

function QueryCta() {
  return (
    <Link to="/runs">
      <Card className="group flex items-center gap-4 px-5 py-4 transition-colors hover:border-indigo-400/60">
        <span className="flex h-11 w-11 shrink-0 items-center justify-center rounded-xl bg-indigo-500/15 text-indigo-300">
          <SearchCheck className="h-5 w-5" />
        </span>
        <span className="min-w-0 flex-1">
          <span className="block text-sm font-semibold text-white">
            What would you like to research?
          </span>
          <span className="block truncate text-xs text-terminal-muted">
            Ask any question — the agent searches the live web and returns a source-backed report.
          </span>
        </span>
        <span className="inline-flex shrink-0 items-center gap-1.5 rounded-md bg-indigo-500 px-3.5 py-2 text-sm font-medium text-white group-hover:bg-indigo-400">
          <PlayCircle className="h-4 w-4" /> Start research
        </span>
      </Card>
    </Link>
  );
}

function RecentRuns({ runs }: { runs: ResearchRun[] }) {
  if (runs.length === 0) return null;
  return (
    <Card>
      <CardHeader
        title="Recent runs"
        action={
          <Link to="/runs">
            <Button variant="ghost" className="text-xs">
              All runs <ArrowRight className="h-3.5 w-3.5" />
            </Button>
          </Link>
        }
      />
      <ul className="divide-y divide-terminal-border/50">
        {runs.map((r) => (
          <li key={r.run_id} className="flex items-center gap-3 px-5 py-3">
            <RunStatusBadge status={r.status} />
            <Link
              to={`/runs/${r.run_id}`}
              className="min-w-0 flex-1 truncate text-sm text-terminal-text hover:underline"
              title={r.query ?? r.run_id}
            >
              {r.mode === "query" ? r.query : r.request?.tickers
                ? `${(r.request.tickers as string[]).length} tickers`
                : "FTSE 50"}
            </Link>
            <span className="hidden text-xs text-terminal-faint sm:block">
              {timeAgo(r.finished_at ?? r.created_at)}
            </span>
            {r.report_id && isTerminal(r.status) && (
              <Link to={`/reports/${r.report_id}`} className="text-xs text-indigo-300 hover:underline">
                Report
              </Link>
            )}
          </li>
        ))}
      </ul>
    </Card>
  );
}

/* ------------------------- Query report summary ------------------------- */

function QueryReportSummary({ report }: { report: ReportDetail }) {
  const findings = report.findings;
  const avgRelevance =
    findings.length > 0
      ? findings.reduce((s, f) => s + f.relevance, 0) / findings.length
      : 0;
  const high = findings.filter((f) => f.impact === "high").length;
  const meta = report.metadata as { counts?: Record<string, unknown> };
  const counts = (meta.counts ?? {}) as Record<string, unknown>;

  return (
    <div className="space-y-6">
      <div className="grid grid-cols-2 gap-4 lg:grid-cols-4">
        <Stat label="Findings" value={findings.length} icon={<Newspaper className="h-4 w-4" />} sub={`Report ${report.summary.date}`} />
        <Stat label="Avg relevance" value={`${Math.round(avgRelevance * 100)}%`} icon={<SearchCheck className="h-4 w-4" />} />
        <Stat label="High-impact" value={high} icon={<Flame className="h-4 w-4" />} />
        <Stat label="Articles extracted" value={String(counts.extracted ?? "—")} icon={<FileText className="h-4 w-4" />} />
      </div>
      <Card>
        <CardHeader
          title={report.query ?? "Latest query report"}
          subtitle={`${findings.length} ranked findings · ${report.summary.id}`}
          action={
            <Link to={`/reports/${report.summary.id}`}>
              <Button variant="ghost" className="text-xs">
                Full report <ArrowUpRight className="h-3.5 w-3.5" />
              </Button>
            </Link>
          }
        />
        <ol className="divide-y divide-terminal-border/50">
          {findings.slice(0, 5).map((f, i) => (
            <li key={f.url} className="px-5 py-3.5">
              <div className="flex items-start gap-3">
                <span className="mt-0.5 flex h-6 w-6 shrink-0 items-center justify-center rounded-md bg-indigo-500/10 font-mono text-[11px] text-indigo-300">
                  {i + 1}
                </span>
                <div className="min-w-0">
                  <Link to={`/reports/${report.summary.id}`} className="font-medium text-white hover:underline">
                    {f.title}
                  </Link>
                  <p className="mt-0.5 truncate text-sm text-terminal-muted">{f.key_finding}</p>
                  <div className="mt-1.5 flex flex-wrap items-center gap-2 text-xs text-terminal-faint">
                    <span className="tabular-nums">{Math.round(f.relevance * 100)}% relevant</span>
                    <Badge tone={impactTone(f.impact)}>{f.impact}</Badge>
                    <span>{f.source || hostOf(f.url)}</span>
                  </div>
                </div>
              </div>
            </li>
          ))}
        </ol>
      </Card>
    </div>
  );
}

/* -------------------------- FTSE report summary -------------------------- */

function FtseReportSummary({
  report,
  activeRun,
}: {
  report: ReportDetail;
  activeRun: ResearchRun | null;
}) {
  const [selected, setSelected] = useState<ArticleWithCompany | null>(null);

  const articles: ArticleWithCompany[] = useMemo(
    () =>
      report.companies.flatMap((c) =>
        c.articles.map((a) => ({
          ...a,
          company: c.company,
          ticker: c.ticker,
          report_id: report.summary.id,
        }))
      ),
    [report]
  );

  const stats = useMemo(() => {
    const positive = articles.filter((a) => a.sentiment === "positive").length;
    const negative = articles.filter((a) => a.sentiment === "negative").length;
    const high = articles.filter((a) => a.impact === "high").length;
    return { companies: report.companies.length, articles: articles.length, positive, negative, high };
  }, [articles, report]);

  const sentimentData = useMemo(() => {
    const counts: Record<string, number> = { positive: 0, negative: 0, neutral: 0 };
    articles.forEach((a) => {
      counts[a.sentiment] = (counts[a.sentiment] ?? 0) + 1;
    });
    return Object.entries(counts)
      .filter(([, v]) => v > 0)
      .map(([name, value]) => ({ name, value }));
  }, [articles]);

  const impactData = useMemo(() => {
    const order = ["high", "medium", "low"];
    const counts: Record<string, number> = { high: 0, medium: 0, low: 0 };
    articles.forEach((a) => {
      counts[a.impact] = (counts[a.impact] ?? 0) + 1;
    });
    return order.map((name) => ({ name, value: counts[name] ?? 0 }));
  }, [articles]);

  const coverageData = useMemo(
    () =>
      report.companies
        .map((c) => ({ name: c.ticker, articles: c.articles.length }))
        .sort((a, b) => b.articles - a.articles)
        .slice(0, 10),
    [report]
  );

  const failedCompanies = report.companies.filter((c) => c.articles.length === 0);
  const topArticles = [...articles]
    .sort((a, b) => {
      const rank = { high: 0, medium: 1, low: 2 };
      return (rank[a.impact] ?? 2) - (rank[b.impact] ?? 2) || b.confidence - a.confidence;
    })
    .slice(0, 8);

  const tooltipStyle = {
    backgroundColor: "#151d30",
    border: "1px solid #1e2a44",
    borderRadius: 8,
    fontSize: 12,
    color: "#dbe4f5",
  };

  return (
    <div className="space-y-6">
      {activeRun && (
        <Alert tone="info">
          Figures below are from the last completed FTSE report.
        </Alert>
      )}
      {failedCompanies.length > 0 && (
        <Alert>
          Partial results: {failedCompanies.length} of {report.companies.length} companies
          produced no articles.
        </Alert>
      )}

      <div className="grid grid-cols-2 gap-4 lg:grid-cols-5">
        <Stat label="Companies covered" value={stats.companies} icon={<Building2 className="h-4 w-4" />} sub={`Report ${report.summary.date}`} />
        <Stat label="Relevant articles" value={stats.articles} icon={<Newspaper className="h-4 w-4" />} />
        <Stat label="Positive signals" value={stats.positive} icon={<ThumbsUp className="h-4 w-4" />} />
        <Stat label="Negative signals" value={stats.negative} icon={<ThumbsDown className="h-4 w-4" />} />
        <Stat label="High-impact articles" value={stats.high} icon={<Flame className="h-4 w-4" />} />
      </div>

      <div className="grid gap-4 lg:grid-cols-3">
        <Card>
          <CardHeader title="Sentiment distribution" subtitle="Across all ranked articles" />
          <div className="h-56 px-2 pb-2">
            {sentimentData.length === 0 ? (
              <ChartEmpty />
            ) : (
              <ResponsiveContainer width="100%" height="100%">
                <PieChart>
                  <Pie data={sentimentData} dataKey="value" nameKey="name" innerRadius={45} outerRadius={75} paddingAngle={2}>
                    {sentimentData.map((d) => (
                      <Cell key={d.name} fill={SENTIMENT_COLORS[d.name] ?? "#8b98b8"} />
                    ))}
                  </Pie>
                  <Tooltip contentStyle={tooltipStyle} />
                </PieChart>
              </ResponsiveContainer>
            )}
          </div>
          <Legend items={sentimentData.map((d) => ({ label: d.name, value: d.value, color: SENTIMENT_COLORS[d.name] }))} />
        </Card>

        <Card>
          <CardHeader title="Impact distribution" subtitle="Financial materiality" />
          <div className="h-56 px-2 pb-2">
            <ResponsiveContainer width="100%" height="100%">
              <BarChart data={impactData} margin={{ top: 8, right: 8, left: -18, bottom: 0 }}>
                <CartesianGrid stroke="#1e2a44" strokeDasharray="3 3" vertical={false} />
                <XAxis dataKey="name" tick={{ fill: "#8b98b8", fontSize: 12 }} tickLine={false} axisLine={{ stroke: "#1e2a44" }} />
                <YAxis allowDecimals={false} tick={{ fill: "#8b98b8", fontSize: 12 }} tickLine={false} axisLine={false} />
                <Tooltip contentStyle={tooltipStyle} cursor={{ fill: "#ffffff08" }} />
                <Bar dataKey="value" radius={[4, 4, 0, 0]}>
                  {impactData.map((d) => (
                    <Cell key={d.name} fill={IMPACT_COLORS[d.name] ?? "#8b98b8"} />
                  ))}
                </Bar>
              </BarChart>
            </ResponsiveContainer>
          </div>
        </Card>

        <Card>
          <CardHeader title="Coverage by company" subtitle="Top 10 by article count" />
          <div className="h-56 px-2 pb-2">
            {coverageData.every((d) => d.articles === 0) ? (
              <ChartEmpty />
            ) : (
              <ResponsiveContainer width="100%" height="100%">
                <BarChart data={coverageData} layout="vertical" margin={{ top: 0, right: 12, left: 8, bottom: 0 }}>
                  <CartesianGrid stroke="#1e2a44" strokeDasharray="3 3" horizontal={false} />
                  <XAxis type="number" allowDecimals={false} tick={{ fill: "#8b98b8", fontSize: 11 }} tickLine={false} axisLine={false} />
                  <YAxis type="category" dataKey="name" width={64} tick={{ fill: "#8b98b8", fontSize: 11, fontFamily: "monospace" }} tickLine={false} axisLine={false} />
                  <Tooltip contentStyle={tooltipStyle} cursor={{ fill: "#ffffff08" }} />
                  <Bar dataKey="articles" fill="#818cf8" radius={[0, 4, 4, 0]} />
                </BarChart>
              </ResponsiveContainer>
            )}
          </div>
        </Card>
      </div>

      <Card>
        <CardHeader
          title="Key articles"
          subtitle={`${topArticles.length} highest-ranked from ${report.summary.id}`}
          action={
            <Link to={`/reports/${report.summary.id}`}>
              <Button variant="ghost" className="text-xs">
                Full report <ArrowUpRight className="h-3.5 w-3.5" />
              </Button>
            </Link>
          }
        />
        <div className="overflow-x-auto">
          <table className="w-full min-w-[880px] text-left text-sm">
            <thead>
              <tr className="border-b border-terminal-border text-xs uppercase tracking-wide text-terminal-faint">
                <th className="px-5 py-3 font-medium">Company</th>
                <th className="px-3 py-3 font-medium">Headline</th>
                <th className="px-3 py-3 font-medium">Source</th>
                <th className="px-3 py-3 font-medium">Published</th>
                <th className="px-3 py-3 font-medium">Sentiment</th>
                <th className="px-3 py-3 font-medium">Impact</th>
                <th className="px-3 py-3 font-medium">Conf.</th>
                <th className="px-3 py-3 font-medium">Links</th>
              </tr>
            </thead>
            <tbody>
              {topArticles.map((a) => (
                <tr
                  key={`${a.ticker}-${a.url}`}
                  className="cursor-pointer border-b border-terminal-border/50 transition-colors last:border-0 hover:bg-white/[0.02]"
                  onClick={() => setSelected(a)}
                >
                  <td className="px-5 py-3">
                    <div className="font-medium text-white">{a.company}</div>
                    <div className="font-mono text-xs text-terminal-faint">{a.ticker}</div>
                  </td>
                  <td className="max-w-[320px] px-3 py-3">
                    <div className="truncate font-medium text-terminal-text" title={a.title}>{a.title}</div>
                    {a.reason && (
                      <div className="mt-0.5 truncate text-xs text-terminal-faint" title={a.reason}>{a.reason}</div>
                    )}
                  </td>
                  <td className="whitespace-nowrap px-3 py-3 text-xs text-terminal-muted">{a.source || hostOf(a.url)}</td>
                  <td className="whitespace-nowrap px-3 py-3 text-xs text-terminal-muted">{formatDate(a.published_at)}</td>
                  <td className="px-3 py-3"><Badge tone={sentimentTone(a.sentiment)}>{a.sentiment}</Badge></td>
                  <td className="px-3 py-3"><Badge tone={impactTone(a.impact)}>{a.impact}</Badge></td>
                  <td className="px-3 py-3 tabular-nums text-terminal-muted">{formatConfidence(a.confidence)}</td>
                  <td className="px-3 py-3">
                    <div className="flex items-center gap-1">
                      <button
                        className="rounded p-1.5 text-terminal-muted hover:bg-white/5 hover:text-white"
                        title="View details"
                        onClick={(e) => { e.stopPropagation(); setSelected(a); }}
                      >
                        <FileText className="h-4 w-4" />
                      </button>
                      <a
                        href={a.url}
                        target="_blank"
                        rel="noopener noreferrer"
                        className="rounded p-1.5 text-terminal-muted hover:bg-white/5 hover:text-white"
                        title="Open original article"
                        onClick={(e) => e.stopPropagation()}
                      >
                        <ExternalLink className="h-4 w-4" />
                      </a>
                    </div>
                  </td>
                </tr>
              ))}
            </tbody>
          </table>
        </div>
      </Card>

      <ArticleDialog article={selected} onClose={() => setSelected(null)} />
    </div>
  );
}

function ChartEmpty() {
  return (
    <div className="flex h-full items-center justify-center text-xs text-terminal-faint">
      No data to chart
    </div>
  );
}

function Legend({ items }: { items: { label: string; value: number; color: string }[] }) {
  return (
    <div className="flex flex-wrap gap-x-4 gap-y-1 px-5 pb-4">
      {items.map((i) => (
        <span key={i.label} className="inline-flex items-center gap-1.5 text-xs capitalize text-terminal-muted">
          <span className="h-2.5 w-2.5 rounded-full" style={{ backgroundColor: i.color }} />
          {i.label} · <span className="tabular-nums text-white">{i.value}</span>
        </span>
      ))}
    </div>
  );
}
